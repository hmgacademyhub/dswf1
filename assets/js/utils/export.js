  async function exportPDF(title, sections, filename = 'report.pdf') {
    if (typeof window.jspdf === 'undefined') return;
    const { jsPDF } = window.jspdf;
    const doc = new jsPDF();
    doc.setFontSize(20);
    doc.setTextColor(246, 196, 83);
    doc.text(title, 20, 20);
    doc.setFontSize(10);
    doc.setTextColor(100);
    doc.text(`DataFlow Studio v14.0 — HMG Academy Edition — ${new Date().toLocaleString()}`, 20, 28);

    let y = 40;
    const pageHeight = doc.internal.pageSize.height;
    const margin = 20;

    sections.forEach(section => {
      if (y > pageHeight - margin) { doc.addPage(); y = 20; }
      if (section.type === 'heading') {
        doc.setFontSize(14); doc.setTextColor(0, 0, 0);
        doc.text(section.text, margin, y); y += 8;
      } else if (section.type === 'text') {
        doc.setFontSize(11); doc.setTextColor(60);
        const lines = doc.splitTextToSize(section.text, 170);
        lines.forEach(line => {
          if (y > pageHeight - margin) { doc.addPage(); y = 20; }
          doc.text(line, margin, y); y += 6;
        });
        y += 4;
      } else if (section.type === 'table') {
        doc.setFontSize(9); doc.setTextColor(0, 0, 0);
        const colWidth = 80;
        section.headers.forEach((h, i) => doc.text(h, margin + i * colWidth, y));
        y += 6;
        section.rows.forEach(row => {
          if (y > pageHeight - margin) { doc.addPage(); y = 20; }
          row.forEach((cell, i) => doc.text(String(cell).substring(0, 30), margin + i * colWidth, y));
          y += 6;
        });
        y += 4;
      }
    });

    const totalPages = doc.internal.getNumberOfPages();
    for (let p = 1; p <= totalPages; p++) {
      doc.setPage(p);
      doc.setFontSize(8);
      doc.setTextColor(120);
      doc.text(`© 2026 HMG Academy — DataFlow Studio v14.0 — Page ${p} of ${totalPages}`, margin, pageHeight - 10);
    }
    doc.save(filename);
  }

  function encodeShareURL(data) {
    const json = JSON.stringify(data);
    const encoded = btoa(encodeURIComponent(json));
    return `${location.origin}${location.pathname}#data=${encoded}`;
  }

  function decodeShareURL() {
    const hash = location.hash;
    if (!hash.startsWith('#data=')) return null;
    try {
      const encoded = hash.substring(6);
      const json = decodeURIComponent(atob(encoded));
      return JSON.parse(json);
    } catch (e) { return null; }
  }

  function copyShareURL(data) {
    const url = encodeShareURL(data);
    navigator.clipboard.writeText(url).catch(() => prompt('Copy:', url));
    return url;
  }

  function download(content, filename, mimeType) {
    const blob = new Blob([content], { type: mimeType });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url; a.download = filename;
    document.body.appendChild(a); a.click(); document.body.removeChild(a);
    URL.revokeObjectURL(url);
  }

